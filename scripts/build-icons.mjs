// The gallery's icon set (COMMON-PROJECT-SPEC C11): one drawing — a light
// spiral on the gallery's dark ground, the vector heir of the 🌀 emoji the
// pages used as their favicon — written as the three SVG sources, then
// rasterised into every PNG a browser or a phone asks for, and a favicon.ico.
// Everything lands in site/, which scripts/copy-site.js copies to the root of
// the built gallery; the files are committed, because GitHub Pages rasterises
// nothing.
//
//   npm i --no-save sharp   (once; deliberately NOT a dependency: this runs by
//                           hand, and CI would pay for a native install on
//                           every job. A top-level install prunes the gallery
//                           package's own dependencies: run
//                           `npm install --prefix ./node_modules/sketch-gallery`
//                           again before the next build.)
//   npm run icons
//
// Re-run after changing the drawing and commit the sources and the PNGs
// together; tests/icons.test.js holds the sizes and the touch icon's lack of
// alpha (iOS composites a transparent pixel onto black).

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SITE = join(dirname(fileURLToPath(import.meta.url)), "..", "site");

// The gallery's own two colours (sketch-gallery's --dark-color and
// --light-color), so the icon belongs to the page it stands for.
export const DARK = "#1e1d1d";
export const LIGHT = "#f9f7f2";

// An Archimedean spiral, r = r0 + b·θ, from the centre outwards, in a 512
// box. Under two turns with a thick stroke, so its arms stay apart at 16 px
// (a stroke and a gap of about 1.6 px each).
export function spiralPath({ turns = 1.75, inner = 18, outer = 178, stroke = 50, steps = 240 } = {}) {
  const span = turns * 2 * Math.PI;
  const b = (outer - inner) / span;
  const points = [];
  for (let i = 0; i <= steps; i += 1) {
    const t = (span * i) / steps;
    const r = inner + b * t;
    // Starts pointing up and winds clockwise, like the emoji's swirl.
    points.push([r * Math.sin(t), -r * Math.cos(t)]);
  }
  // Centres the drawing on its own bounding box, stroke included: an
  // Archimedean spiral is lopsided around its pole.
  const xs = points.map((p) => p[0]);
  const ys = points.map((p) => p[1]);
  const cx = (Math.min(...xs) + Math.max(...xs)) / 2;
  const cy = (Math.min(...ys) + Math.max(...ys)) / 2;
  const extent = Math.max(Math.max(...xs) - Math.min(...xs), Math.max(...ys) - Math.min(...ys)) / 2 + stroke / 2;
  const d = points
    .map(([x, y], i) => `${i ? "L" : "M"}${(256 + x - cx).toFixed(1)} ${(256 + y - cy).toFixed(1)}`)
    .join("");
  return { d, stroke, extent };
}

function spiral(scale = 1) {
  const { d, stroke } = spiralPath();
  const transform = scale === 1 ? "" : ` transform="translate(256 256) scale(${scale}) translate(-256 -256)"`;
  return (
    `<path d="${d}" fill="none" stroke="${LIGHT}" stroke-width="${stroke}" ` +
    `stroke-linecap="round" stroke-linejoin="round"${transform}/>`
  );
}

const svg = (comment, body) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">\n  <!-- ${comment} -->\n  ${body}\n</svg>\n`;

// The maskable art fits the centred circle of 80 % diameter (radius 204.8),
// so no launcher mask shaves the spiral.
const maskScale = Math.min(1, 204.8 / spiralPath().extent);

export const SOURCES = {
  "icon.svg": svg(
    "Generated by scripts/build-icons.mjs. The tab icon: a rounded dark tile, transparent corners.",
    `<rect width="512" height="512" rx="104" fill="${DARK}"/>\n  ${spiral()}`,
  ),
  "icon-apple.svg": svg(
    "Generated by scripts/build-icons.mjs. Full bleed and opaque: iOS draws its own corners.",
    `<rect width="512" height="512" fill="${DARK}"/>\n  ${spiral()}`,
  ),
  "icon-maskable.svg": svg(
    "Generated by scripts/build-icons.mjs. Full bleed, the spiral inside the 80 % safe zone.",
    `<rect width="512" height="512" fill="${DARK}"/>\n  ${spiral(Number(maskScale.toFixed(3)))}`,
  ),
};

export const RASTERS = [
  { src: "icon.svg", out: "favicon-16.png", size: 16 },
  { src: "icon.svg", out: "favicon-32.png", size: 32 },
  { src: "icon.svg", out: "icon-96.png", size: 96 },
  { src: "icon.svg", out: "icon-192.png", size: 192 },
  { src: "icon.svg", out: "icon-512.png", size: 512 },
  { src: "icon-maskable.svg", out: "icon-maskable-192.png", size: 192 },
  { src: "icon-maskable.svg", out: "icon-maskable-512.png", size: 512 },
  { src: "icon-apple.svg", out: "apple-touch-icon.png", size: 180, opaque: true },
];

// A favicon.ico that embeds PNGs (every browser since Windows Vista's era).
export function ico(images) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(1, 2); // type: icon
  header.writeUInt16LE(images.length, 4);
  let offset = 6 + 16 * images.length;
  const entries = images.map(({ png, size }) => {
    const entry = Buffer.alloc(16);
    entry[0] = size >= 256 ? 0 : size;
    entry[1] = size >= 256 ? 0 : size;
    entry.writeUInt16LE(1, 4); // colour planes
    entry.writeUInt16LE(32, 6); // bits per pixel
    entry.writeUInt32LE(png.length, 8);
    entry.writeUInt32LE(offset, 12);
    offset += png.length;
    return entry;
  });
  return Buffer.concat([header, ...entries, ...images.map(({ png }) => png)]);
}

async function main() {
  const { default: sharp } = await import("sharp");
  const raster = (source, size, opaque = false) => {
    let image = sharp(Buffer.from(source), { density: 384 }).resize(size, size);
    if (opaque) image = image.flatten({ background: DARK }).removeAlpha();
    return image.png({ compressionLevel: 9 }).toBuffer();
  };

  for (const [name, source] of Object.entries(SOURCES)) writeFileSync(join(SITE, name), source);
  for (const job of RASTERS) {
    writeFileSync(join(SITE, job.out), await raster(SOURCES[job.src], job.size, job.opaque));
    console.log(`${job.out.padEnd(24)} ${job.size}×${job.size}${job.opaque ? "  opaque" : ""}`);
  }
  const sizes = [16, 32, 48];
  const pngs = await Promise.all(sizes.map((size) => raster(SOURCES["icon.svg"], size)));
  writeFileSync(join(SITE, "favicon.ico"), ico(pngs.map((png, i) => ({ png, size: sizes[i] }))));
  console.log(`${"favicon.ico".padEnd(24)} ${sizes.join(", ")}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
